-- ركن الاتحاد: من "مرة وحدة لكل قسم بطول الفعالية" إلى "مرة وحدة لكل قسم باليوم"
-- ---------------------------------------------------------------------------
-- يوسّع القيد بدل ما يشدده: الفهرس القديم كان (student_id, union_section)
-- فبطل على نفس القسم مرتين بأي يوم من أيام الفعالية. الجديد بيضيف
-- CAST(checked_in_at AS DATE) كعمود ثالث، فصار المسح مسموح مرة وحدة لكل قسم
-- لكل يوم — نفس نمط unique_campus_entry_checkin و unique_lecture_checkin.
--
-- كل السجلات الموجودة مسبقاً بتلتزم بالقيد الجديد (أضيق ← أوسع)، فما في
-- أي تعديل على البيانات ولا إعادة زرع ولا حذف.
--
-- يُطبَّق على قواعد التطوير والإنتاج (حيث انطبّق migration_union_sections.sql
-- سابقاً). ملاحظة: الفهرس القديم يُحذف أولاً لأن PostgreSQL ما بيسمح بإعادة
-- تعريف فهرس بنفس الاسم بـ IF NOT EXISTS.
--
-- صيحة للقواعد الجديدة (create_all): الموديل يبني الفهرس بأعمدته الثلاثة تلقائياً.
--
-- الاستخدام (من جذر المشروع):
--     python scripts/run_sql_migration.py   ← بعد ضبط ملف الـ SQL المطلوب
-- أو عبر psql مباشرة على القاعدة المستهدفة.
-- ---------------------------------------------------------------------------

BEGIN;

DROP INDEX IF EXISTS unique_union_checkin;

CREATE UNIQUE INDEX unique_union_checkin
    ON checkins (student_id, union_section, CAST(checked_in_at AS DATE))
    WHERE activity_type = 'union';

COMMIT;
